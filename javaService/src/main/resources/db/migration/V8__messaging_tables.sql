-- Журнал обработки входящих событий: идемпотентность консьюмеров ядра
-- при at-least-once доставке Kafka.
CREATE TABLE processed_events (
    event_id     VARCHAR(64) NOT NULL,
    consumer     VARCHAR(64) NOT NULL,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (event_id, consumer)
);

-- Журнал команд ядра транспорту: по нему DeliveryResult сопоставляется
-- с целью команды (подтверждение/удаление/напоминание).
CREATE TABLE outbound_commands (
    command_id          VARCHAR(64)  NOT NULL PRIMARY KEY,
    type                VARCHAR(32)  NOT NULL,
    channel             VARCHAR(32)  NOT NULL,
    conversation_id     VARCHAR(255) NOT NULL,
    purpose             VARCHAR(32)  NOT NULL,
    related_id          BIGINT       NULL,
    status              VARCHAR(16)  NOT NULL,
    external_message_id VARCHAR(64)  NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_outbound_commands_related ON outbound_commands (related_id, purpose);

-- Напоминания по записям. Уникальность (schedule_id, kind) не даёт создать
-- дубли при повторной обработке события создания.
CREATE TABLE reminders (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT      NOT NULL,
    kind        VARCHAR(32) NOT NULL,
    remind_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    status      VARCHAR(16) NOT NULL,
    attempts    INT         NOT NULL DEFAULT 0,
    claimed_at  TIMESTAMP WITH TIME ZONE NULL,
    sent_at     TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT uk_reminders_schedule_kind UNIQUE (schedule_id, kind)
);
