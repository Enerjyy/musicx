-- Разделяем «пользователя» и «способ входа».
--
-- До этой миграции telegram_id жил прямо в user_entity. Это работает, пока
-- способ входа один, но второй (Google, Discord) потребовал бы либо новых
-- колонок на каждый провайдер, либо невалидного состояния, когда
-- telegram_id пустой. Поэтому идентификаторы провайдеров переезжают в
-- отдельную таблицу, а user_entity остаётся «кто это» без привязки к входу.
--
-- Миграция идемпотентна по данным: существующие telegram_id переносятся в
-- user_identity, поэтому уже зарегистрированные пользователи не потеряются.

CREATE TABLE user_identity (
    identity_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    provider         VARCHAR(32)  NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    CONSTRAINT fk_user_identity_user
        FOREIGN KEY (user_id) REFERENCES user_entity (user_id) ON DELETE CASCADE,
    CONSTRAINT uk_user_identity_provider UNIQUE (provider, provider_user_id)
);

-- Переносим существующие Telegram-аккаунты. NULL не переносим: у пользователя
-- без telegram_id нет способа входа, и создавать для него связку нельзя.
INSERT INTO user_identity (user_id, provider, provider_user_id)
SELECT user_id, 'TELEGRAM', CAST(telegram_id AS VARCHAR(255))
FROM user_entity
WHERE telegram_id IS NOT NULL;

-- Старая колонка больше не нужна. Уникальный констрейнт снимаем вместе с ней.
ALTER TABLE user_entity DROP CONSTRAINT IF EXISTS uk_user_entity_telegram_id;
ALTER TABLE user_entity DROP COLUMN IF EXISTS telegram_id;