CREATE TABLE user_schedules (
    scedule_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    title       VARCHAR(255) NOT NULL,
    note        VARCHAR(255) NOT NULL,
    date        DATE         NOT NULL,
    time        TIME         NOT NULL
);

CREATE INDEX ix_user_schedules_user_date ON user_schedules (user_id, date, time);