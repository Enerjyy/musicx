-- Задачи отложенного удаления подтверждений создания записи.
--
-- Хранятся в ядре: рестарт сервиса не оставляет «висящее» сообщение,
-- просроченные задачи подхватываются планировщиком на первом тике.
CREATE TABLE scheduled_deletions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel             VARCHAR(32)  NOT NULL,
    conversation_id     VARCHAR(255) NOT NULL,
    external_message_id VARCHAR(64)  NOT NULL,
    delete_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    status              VARCHAR(16)  NOT NULL,
    attempts            INT          NOT NULL DEFAULT 0,
    claimed_at          TIMESTAMP WITH TIME ZONE NULL,
    command_id          VARCHAR(64)  NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_scheduled_deletions_message
        UNIQUE (channel, conversation_id, external_message_id)
);

CREATE INDEX ix_scheduled_deletions_due ON scheduled_deletions (status, delete_at);
