package enerjy.musicxService.user;

/** Тип напоминания. Новое значение не требует миграции (пишется строкой). */
public enum ReminderKind {

    /** За N часов до начала (N настраивается, сейчас 3 часа). */
    T_MINUS_3H,

    /**
     * Ровно в 00:00 дня события (в зоне записи) — для записей «весь день».
     * Уникальный ключ (schedule_id, kind) не конфликтует с {@link #T_MINUS_3H}:
     * у одной записи могут быть оба типа (после переноса обычной записи в
     * «весь день» старое T_MINUS_3H удаляется, но пары видов не пересекаются).
     */
    MIDNIGHT
}
