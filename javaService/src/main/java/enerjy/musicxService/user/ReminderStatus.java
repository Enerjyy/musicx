package enerjy.musicxService.user;

/** Жизненный цикл напоминания. */
public enum ReminderStatus {

    /** Ждёт отправки планировщиком. */
    PENDING,

    /** Захвачено тиком планировщика, отправка в процессе. */
    SENDING,

    /** Отправлено, подтверждено DeliveryResult. */
    SENT,

    /** Отправка не нужна: запись создана слишком поздно. */
    SKIPPED,

    /** Временные сбои исчерпали попытки. */
    FAILED,

    /** Постоянный отказ (например, бот заблокирован). */
    FAILED_PERMANENT,

    /** Начало события уже прошло — отправлять поздно. */
    EXPIRED
}
