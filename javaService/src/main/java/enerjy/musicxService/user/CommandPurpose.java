package enerjy.musicxService.user;

/** Зачем ядру эта команда: связывает DeliveryResult с целью отправки. */
public enum CommandPurpose {

    /** Подтверждение создания записи (удаляется через 30 с, Шаг 6). */
    CONFIRM_SCHEDULE,

    /** Подтверждение переноса (правки) существующей записи. */
    CONFIRM_UPDATE,

    /** Подтверждение удаления записи (запись уходит в CANCELED). */
    CONFIRM_DELETE,

    /**
     * Уточняющий вопрос при правке/удалении: кандидатов 0 или больше одного —
     * запись не трогаем, пока пользователь не опишет её точнее.
     */
    CLARIFY_SCHEDULE,

    /** Фоновое удаление сообщения. */
    DELETE_CONFIRMATION,

    /** Напоминание о событии. */
    REMINDER
}
