package enerjy.musicxService.user;

/** Жизненный цикл отложенного удаления сообщения. */
public enum DeletionStatus {

    /** Ждёт планового тика планировщика. */
    PENDING,

    /** Захвачено тиком, команда удаления отправляется. */
    SENDING,

    /** Удалено или удалять уже нечего (ALREADY_GONE). */
    DONE,

    /** Окончательный отказ (например, канал недоступен этому пользователю). */
    FAILED
}
