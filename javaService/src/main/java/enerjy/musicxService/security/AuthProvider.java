package enerjy.musicxService.security;

/**
 * Способ входа пользователя.
 *
 * Провайдер — это «кто удостоверил личность»: Telegram Mini App, Google,
 * Discord и так далее. Каждому новому провайдеру нужна своя проверка
 * (аналог {@code TGDataValidation}), но остальная система — токены, фильтр,
 * контроллеры — про провайдере ничего не знает и не меняется.
 *
 * Значение enum пишется в БД как строка (`@Enumerated(EnumType.STRING)`),
 * поэтому колонка VARCHAR и добавление нового провайдера не требует миграции.
 *
 * Чтобы добавить провайдера: дописать значение сюда, написать верификатор и
 * добавить ветку в контроллер логина. Всё.
 */
public enum AuthProvider {

    /** Telegram Mini App: личность подтверждается подписанным initData. */
    TELEGRAM;

}